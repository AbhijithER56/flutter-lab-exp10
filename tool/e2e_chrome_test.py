"""End-to-end test of the Flutter web build in real Chrome against the REAL
Cloud Firestore `users` collection, plus output screenshots.

Usage (from the project root, after `flutter build web`):
    set E2E_EMAIL=<email of a user added in Firebase Console>
    set E2E_PASSWORD=<that user's password>
    python tool/e2e_chrome_test.py screenshots

Users are added manually in the Firebase Console. This script never writes to
Firestore; it only reads the test user's name/email/phone through the REST API
to check that the dashboard shows the right details. Passwords are never printed.
"""
import json, os, subprocess, sys, time, urllib.parse, urllib.request
from playwright.sync_api import sync_playwright, expect

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORT = 8780
URL = f"http://127.0.0.1:{PORT}/"
ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
SHOTS = os.path.abspath(ARGS[0] if ARGS else "screenshots")
os.makedirs(SHOTS, exist_ok=True)

EMAIL = os.environ.get("E2E_EMAIL", "").strip()
PASSWORD = os.environ.get("E2E_PASSWORD", "")

# Real project config generated by `flutterfire configure`.
opts = open(os.path.join(ROOT, "lib", "firebase_options.dart"), encoding="utf-8").read()
PROJECT = opts.split("projectId: '")[1].split("'")[0]
API_KEY = opts.split("static const FirebaseOptions web")[1].split("apiKey: '")[1].split("'")[0]
REST = (f"https://firestore.googleapis.com/v1/projects/{PROJECT}"
        f"/databases/(default)/documents/users")

INVALID = "Invalid email or password"


def step(msg):
    print(msg, flush=True)


def rest_users():
    """{doc id: {"name", "email", "phone", "updateTime"}} - password not fetched."""
    mask = "".join(f"&mask.fieldPaths={f}" for f in ("name", "email", "phone"))
    with urllib.request.urlopen(f"{REST}?key={API_KEY}&pageSize=300{mask}") as r:
        docs = json.load(r).get("documents", [])
    return {
        d["name"].split("/")[-1]: {
            **{k: d.get("fields", {}).get(k, {}).get("stringValue") for k in ("name", "email", "phone")},
            "updateTime": d["updateTime"],
        }
        for d in docs
    }


def launch(p, viewport=(1280, 860)):
    browser = p.chromium.launch(channel="chrome", headless=True)
    ctx = browser.new_context(viewport={"width": viewport[0], "height": viewport[1]})
    page = ctx.new_page()
    page.on("console", lambda m: m.type == "error" and print("CONSOLE:", m.text))
    return browser, page


def open_app(page):
    page.goto(URL)
    page.wait_for_selector("flt-semantics-placeholder", state="attached", timeout=60000)
    page.locator("flt-semantics-placeholder").dispatch_event("click")
    expect(page.get_by_role("button", name="Login")).to_be_visible(timeout=30000)
    page.wait_for_timeout(800)


def text(page, value, exact=True):
    # Only the visible semantics tree, not Flutter's screen-reader announcements.
    return page.locator("flt-semantics-host").get_by_text(value, exact=exact)


def labelled(page, value):
    # Flutter web merges a Card's texts into one node and exposes them as its
    # aria-label rather than as text content.
    return page.locator(f"flt-semantics-host [aria-label*={json.dumps(value)}]")


def type_into(page, label, value):
    box = page.get_by_role("textbox", name=label)
    box.click()
    page.wait_for_timeout(250)  # let Flutter move focus before typing
    page.keyboard.press("Control+A")
    page.keyboard.press("Backspace")
    if value:
        page.keyboard.type(value, delay=15)


def login(page, email, password):
    type_into(page, "Email", email)
    type_into(page, "Password", password)
    page.get_by_role("button", name="Login").click()


def shot(page, name):
    page.screenshot(path=os.path.join(SHOTS, name))
    step(f"   screenshot -> screenshots/{name}")


def main():
    start = rest_users()
    step(f"Firestore project {PROJECT}: users has {len(start)} docs:")
    for i, u in start.items():
        step(f"   {i}: name={u['name']!r} email={u['email']!r} phone={u['phone']!r}")

    user = next((u for u in start.values()
                 if (u["email"] or "").strip().lower() == EMAIL.lower()), None) if EMAIL else None
    if not EMAIL or not PASSWORD:
        step("NOTE: E2E_EMAIL / E2E_PASSWORD not set - valid-login tests will be skipped")
    elif user is None:
        step(f"NOTE: no users document with email {EMAIL!r} - valid-login tests will be skipped")

    server = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT),
                               "--directory", os.path.join(ROOT, "build", "web")],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1.5)
    skipped = []
    try:
        with sync_playwright() as p:
            browser, page = launch(p)
            open_app(page)
            shot(page, "01_login_screen.png")

            step("TEST 4  Empty email -> validation message")
            login(page, "", "anything")
            expect(text(page, "Please enter your email")).to_be_visible(timeout=10000)
            shot(page, "02_empty_email.png")

            step("TEST 5  Empty password -> validation message")
            login(page, EMAIL or "someone@example.com", "")
            expect(text(page, "Please enter your password")).to_be_visible(timeout=10000)
            shot(page, "03_empty_password.png")

            step("TEST 3  Unknown email -> Invalid email or password (real Firestore query)")
            login(page, "no.such.user.e2e@example.com", "whatever123")
            expect(text(page, INVALID)).to_be_visible(timeout=30000)
            shot(page, "04_unknown_email.png")

            if user:
                step("TEST 2  Correct email + wrong password -> Invalid email or password")
                login(page, EMAIL, PASSWORD + "-wrong")
                expect(text(page, INVALID)).to_be_visible(timeout=30000)
                shot(page, "05_wrong_password.png")

                step("        Show/hide password icon")
                type_into(page, "Password", PASSWORD)
                page.get_by_role("button", name="Show password").click()
                expect(page.get_by_role("button", name="Hide password")).to_be_visible(timeout=5000)
                page.get_by_role("button", name="Hide password").click()
                expect(page.get_by_role("button", name="Show password")).to_be_visible(timeout=5000)

                step("TEST 1  Valid email + password -> Dashboard")
                login(page, EMAIL, PASSWORD)
                expect(labelled(page, f"Welcome, {user['name']}")).to_be_visible(timeout=30000)
                expect(text(page, user["email"], exact=False)).to_be_visible()
                expect(text(page, user["phone"], exact=False)).to_be_visible()
                expect(text(page, PASSWORD, exact=False)).to_have_count(0)
                step(f"   Dashboard shows: Welcome, {user['name']} / {user['email']} / {user['phone']}")
                shot(page, "06_dashboard.png")

                step("TEST 6  Logout -> back to login screen")
                page.get_by_role("button", name="Logout").click()
                expect(text(page, "User Login")).to_be_visible(timeout=10000)
                expect(labelled(page, f"Welcome, {user['name']}")).to_have_count(0)
                shot(page, "07_after_logout.png")
            else:
                skipped += ["valid login", "wrong password", "logout"]
            browser.close()

            step("Responsive layout (phone-size window)")
            browser, page = launch(p, viewport=(412, 915))
            open_app(page)
            shot(page, "08_mobile_login.png")
            if user:
                login(page, EMAIL, PASSWORD)
                expect(labelled(page, f"Welcome, {user['name']}")).to_be_visible(timeout=30000)
                shot(page, "09_mobile_dashboard.png")
            browser.close()

        end = rest_users()
        assert end == start, "the app must never write to the users collection"
        step(f"Firestore users collection unchanged ({len(end)} docs)")
        if skipped:
            step(f"INCOMPLETE: add a user in Firebase Console, set E2E_EMAIL/E2E_PASSWORD "
                 f"and re-run. Skipped: {skipped}")
            sys.exit(2)
        step("ALL E2E TESTS PASSED")
    finally:
        server.terminate()


if __name__ == "__main__":
    main()
